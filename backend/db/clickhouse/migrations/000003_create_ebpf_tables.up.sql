        network_connection_failures UInt64,
        network_avg_rtt_us Float64,
        -- File system metrics
        fs_read_ops UInt64,
        fs_write_ops UInt64,
        fs_bytes_read UInt64,
        fs_bytes_written UInt64,
        fs_read_latency_p95_us Float64,
        fs_write_latency_p95_us Float64,
        fs_read_bandwidth_mbps Float64,
        fs_write_bandwidth_mbps Float64,
        -- Application metrics
        app_db_query_count UInt64,
        app_db_slow_queries UInt64,
        app_cache_hit_rate Float64,
        app_gc_count UInt64,
        app_gc_time_us UInt64,
        -- Security metrics
        security_anomalous_count UInt64,
        security_privilege_escalation_count UInt64,
        security_suspicious_connection_count UInt64,
        security_suspicious_process_count UInt64,
        security_unauthorized_access_count UInt64
    ) ENGINE = ReplacingMergeTree
PARTITION BY
    toYYYYMM (timestamp)
ORDER BY
    (
        organization_id,
        cluster_id,
        container_id,
        timestamp
    );

