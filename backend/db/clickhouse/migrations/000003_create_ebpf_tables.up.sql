        http_error_rate Float64,
        http_latency_p50 Float64,
        http_latency_p95 Float64,
        http_latency_p99 Float64,
        -- Memory metrics
        memory_alloc_count UInt64,
        memory_free_count UInt64,
        memory_bytes_allocated UInt64,
        memory_bytes_freed UInt64,
        memory_net_allocated UInt64,
        memory_page_faults UInt64,
        memory_major_page_faults UInt64,
        memory_gc_count UInt64,
        memory_gc_time_us UInt64,
        -- CPU metrics
        cpu_user_time_us UInt64,
        cpu_system_time_us UInt64,
        cpu_utilization Float64,
        cpu_context_switches UInt64,
        cpu_voluntary_switches UInt64,
        cpu_involuntary_switches UInt64,
